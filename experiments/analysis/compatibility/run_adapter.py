"""Presenting a CORE/netns run to the pipeline in the shape it already knows.

The three-phase pipeline was written against the Shadow tree and reads three
things that no longer exist under that name: a discovery record per
``(run, area)``, a ``shadow.yaml`` for the seed and the GML path, and a level
JSON mapping GML node ids to host names.

Rewriting the pipeline to read the new layout would mean re-deriving every
metric definition, and the point of migrating rather than rewriting is that
the definitions must not change. So the adapter goes the other way: it
*produces* those three inputs from the new run directory, and the pipeline is
untouched apart from learning to discover both layouts.

What the adapter emits lives inside the run, under ``analysis-compat/``, so it
is an artefact of that run and not a hidden global state.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

LOG = logging.getLogger("experiments.analysis.compat")

COMPAT_DIR = "analysis-compat"


def is_native_run(path: Path) -> bool:
    """True when ``path`` is a run directory produced by this harness."""
    path = Path(path)
    return (path / "manifest.json").is_file() and (path / "raw").is_dir()


def discover_native_runs(root: Path) -> list[dict]:
    """Discovery records for every run under a results root.

    The dict shape is exactly the pipeline's: it keys on ``run_id``,
    ``livello`` (here the scenario), ``metrics`` and ``data``. ``livello``
    keeps its Italian name because it is a column in every historical CSV and
    renaming it would break the comparison the migration exists to preserve.
    """
    root = Path(root)
    found: list[dict] = []
    if not root.is_dir():
        LOG.error("results root does not exist: %s", root)
        return found
    for index, run_root in enumerate(sorted(p for p in root.iterdir() if p.is_dir()), 1):
        if not is_native_run(run_root):
            continue
        manifest = json.loads((run_root / "manifest.json").read_text(encoding="utf-8"))
        metrics = run_root / "raw" / "metrics"
        if not metrics.is_dir():
            LOG.warning("%s has no raw/metrics: it produced no chain snapshot", run_root.name)
            continue
        found.append({
            "run_id": manifest.get("run_id", run_root.name),
            "run_dir": run_root.name,
            "run_index": index,
            "tbt_dirname": manifest.get("target_block_time_s", ""),
            "livello": manifest.get("scenario") or manifest.get("experiment") or run_root.name,
            "path": run_root,
            "metrics": metrics,
            "data": run_root / "runtime" / "data",
            "layout": "native",
            "manifest": manifest,
        })
    LOG.info("found %d native runs in %s", len(found), root)
    return found


def write_compat_inputs(run_root: Path, plan) -> dict:
    """Write the level JSON and GML the pipeline expects, from the plan.

    Returns the paths, which the caller passes to the pipeline as
    ``--config-root``. The level JSON reproduces the historical shape exactly:
    a node list carrying the GML id, the host name, the role, the cluster head
    and the coordinates.
    """
    from ...topology import exporters

    compat = Path(run_root) / COMPAT_DIR
    levels = compat / "levels"
    levels.mkdir(parents=True, exist_ok=True)

    gml_ids = _gml_ids(plan.topology)
    nodes = []
    for node in plan.enabled_nodes:
        location = node.location
        entry = {
            "id": gml_ids.get(location, len(nodes)),
            "label": _label(plan.topology, location) or node.id,
            "host": node.id,
            "role": node.role,
        }
        loc = _location(plan.topology, location)
        if loc is not None and loc.lat is not None:
            entry["lat"] = loc.lat
            entry["lon"] = loc.lon
        if node.cluster:
            entry["cluster"] = node.cluster
        nodes.append(entry)

    document = {
        "name": plan.scenario,
        "description": plan.description,
        "source": (
            "generated by experiments.analysis.compatibility.run_adapter from %s; "
            "it is the legacy level-JSON view of the new descriptor, produced so the "
            "migrated pipeline can map GML node ids onto host names without being "
            "rewritten" % plan.descriptor_path.name
        ),
        "nodes": nodes,
        "backbone": _pairs(plan.topology, gml_ids, "backbone"),
        "access": _pairs(plan.topology, gml_ids, "access"),
    }
    level_path = levels / ("%s.json" % plan.scenario)
    level_path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")

    gml_path = compat / "topology.gml"
    exporters.write_gml(plan.topology, gml_path)

    metadata = {
        "general_seed": plan.seed,
        "gml_path": str(gml_path),
        "level_json": str(level_path),
        "env": {
            "POESIA_RNG_SEED": str(plan.seed),
            "POESIA_EPOCHLEN": str(plan.epoch_length),
            "POESIA_SETUPBLOCKS": str(plan.setup_first_blocks),
            "POESIA_CHAIN": plan.multichain.chain,
        },
    }
    (compat / "run-metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    LOG.debug("compatibility inputs written to %s", compat)
    return {"config_root": str(compat), "level_json": str(level_path),
            "gml": str(gml_path), "metadata": str(compat / "run-metadata.json")}


def _gml_ids(topology) -> dict:
    ids: dict[str, int] = {}
    next_id = 0
    for location in topology.locations:
        if location.legacy_gml_id is not None:
            ids[location.id] = location.legacy_gml_id
            next_id = max(next_id, location.legacy_gml_id + 1)
    for location in topology.locations:
        if location.id not in ids:
            ids[location.id] = next_id
            next_id += 1
    return ids


def _location(topology, location_id: str):
    try:
        return topology.location(location_id)
    except KeyError:
        return None


def _label(topology, location_id: str) -> str:
    location = _location(topology, location_id)
    return location.label if location else ""


def _pairs(topology, gml_ids: dict, kind: str) -> list:
    return [
        [gml_ids[link.source], gml_ids[link.target]]
        for link in topology.links
        if link.kind == kind and link.enabled
    ]
