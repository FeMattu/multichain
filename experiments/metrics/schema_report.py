"""Generating ``metrics_schema_report.md`` from the catalogue.

The historical report of the same name was produced by inspecting the files a
campaign happened to contain. This one is generated from the declared
catalogue instead, so it answers the question the old one could not: what
*should* be there, and what is deliberately absent.

Both views are useful, so the generator also takes the observed file list of a
run and reports the two side by side — a column the catalogue promises and the
run did not produce is exactly the kind of silent gap the brief asks not to
have.
"""

from __future__ import annotations

import csv
from pathlib import Path

from .catalogue import ALL_TABLES, DERIVED, OBSERVED, UNAVAILABLE, status_counts

BADGE = {OBSERVED: "observed", DERIVED: "derived", UNAVAILABLE: "**unavailable**"}


def render(observed_files: dict | None = None) -> str:
    """Markdown for the whole catalogue, optionally checked against a run."""
    counts = status_counts()
    lines = [
        "# Metric schema",
        "",
        "Generated by `experiments.metrics.schema_report` from",
        "`experiments/metrics/catalogue.py`, which is the single declaration of what",
        "the harness produces. Editing the table below by hand has no effect: edit the",
        "catalogue.",
        "",
        "Every column carries a status:",
        "",
        "| status | meaning |",
        "|---|---|",
        "| `observed` | read directly from a node, the kernel or the configuration |",
        "| `derived` | computed from observed values by the formula in the source column |",
        "| **`unavailable`** | declared absent, with the reason. Never silently empty. |",
        "",
        "%d observed, %d derived, %d unavailable." % (
            counts[OBSERVED], counts[DERIVED], counts[UNAVAILABLE]),
        "",
        "## Historical tables",
        "",
        "These column names come from the Shadow campaign and are **frozen**: every",
        "archived report and every level-to-level comparison keys on them. New columns",
        "may be appended; existing ones may not be renamed or reordered.",
        "",
    ]
    lines += _tables(t for t in ALL_TABLES if t.historical)
    lines += [
        "",
        "## Tables added by real execution",
        "",
        "Running the real binaries on wall-clock time makes a time series possible",
        "where the simulator only allowed one final snapshot. These tables have no",
        "counterpart in the archived campaign, and their timestamps are **not**",
        "comparable with its simulated time — see [metrics.md](../docs/metrics.md).",
        "",
    ]
    lines += _tables(t for t in ALL_TABLES if not t.historical)

    if observed_files is not None:
        lines += ["", "## What this run actually produced", ""]
        lines += _observed_section(observed_files)
    lines.append("")
    return "\n".join(lines)


def _tables(tables) -> list:
    out = []
    for entry in tables:
        out += [
            "### `%s.csv`" % entry.name,
            "",
            entry.description,
            "",
            "Produced by `%s`." % entry.produced_by,
            "",
            "| column | status | source | unit | meaning |",
            "|---|---|---|---|---|",
        ]
        for column in entry.columns:
            meaning = column.description
            if column.note:
                meaning += " <br> *%s*" % column.note
            out.append("| `%s` | %s | %s | %s | %s |" % (
                column.name, BADGE[column.status], column.source or "-",
                column.unit or "-", meaning))
        out.append("")
    return out


def _observed_section(observed_files: dict) -> list:
    out = ["| file | rows | columns | declared |", "|---|---:|---|---|"]
    declared = {t.name for t in ALL_TABLES}
    for name in sorted(observed_files):
        info = observed_files[name]
        stem = Path(name).stem
        mark = "yes" if stem in declared else "not in the catalogue"
        out.append("| `%s` | %s | %s | %s |" % (
            name, info.get("rows", "?"),
            ", ".join("`%s`" % c for c in info.get("columns", [])[:8]) or "-",
            mark))
    missing = sorted(declared - {Path(n).stem for n in observed_files})
    if missing:
        out += ["", "Declared but not produced by this run: %s." %
                ", ".join("`%s`" % m for m in missing)]
    return out


def inspect_run(metrics_dir: Path) -> dict:
    """Rows and columns of every CSV a run produced."""
    metrics_dir = Path(metrics_dir)
    out: dict = {}
    if not metrics_dir.is_dir():
        return out
    for path in sorted(metrics_dir.glob("*.csv")):
        try:
            with path.open(newline="", encoding="utf-8") as handle:
                reader = csv.reader(handle)
                header = next(reader, [])
                rows = sum(1 for _ in reader)
        except OSError:
            continue
        out[path.name] = {"rows": rows, "columns": header}
    return out


def write(path: Path, metrics_dir: Path | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    observed = inspect_run(metrics_dir) if metrics_dir else None
    path.write_text(render(observed), encoding="utf-8")
    return path
